import Foundation

/// Languages the interface is translated into. The raw values are persisted.
/// The declaration order is also the order of the language picker:
/// Emoji, Simplified Chinese, Traditional Chinese, English, Japanese, Korean,
/// Spanish. "zh" from older builds normalizes to Simplified Chinese.
enum AppLanguage: String, CaseIterable, Identifiable, Sendable {
    case emoji = "emoji"
    case simplifiedChinese = "zh-Hans"
    case traditionalChinese = "zh-Hant"
    case english = "en"
    case japanese = "ja"
    case korean = "ko"
    case spanish = "es"

    var id: String { rawValue }

    /// Shown in the picker in normal languages. The Emoji language itself is
    /// represented by a single glyph so that its UI stays free of English.
    var nativeName: String {
        switch self {
        case .emoji: "Emoji 🎉"
        case .simplifiedChinese: "简体中文"
        case .traditionalChinese: "繁體中文"
        case .english: "English"
        case .japanese: "日本語"
        case .korean: "한국어"
        case .spanish: "Español"
        }
    }

    /// While the Emoji language is active, the picker uses flags so that even
    /// the language menu contains no English words.
    func displayName(in current: AppLanguage) -> String {
        guard current == .emoji else { return nativeName }
        switch self {
        case .emoji: return "🎉"
        case .simplifiedChinese: return "🇨🇳"
        case .traditionalChinese: return "🏮"
        case .english: return "🇬🇧"
        case .japanese: return "🇯🇵"
        case .korean: return "🇰🇷"
        case .spanish: return "🇪🇸"
        }
    }

    /// Device Information still has an English/Chinese technical-label table.
    /// Simplified Chinese, Traditional Chinese and the Emoji Easter egg use
    /// the Chinese table, so no English words leak into those interfaces.
    var usesChineseTechnicalLabels: Bool {
        switch self {
        case .simplifiedChinese, .traditionalChinese, .emoji: true
        case .english, .japanese, .korean, .spanish: false
        }
    }

    static func resolve(_ stored: String) -> AppLanguage {
        if stored == "zh" { return .simplifiedChinese }
        // The removed Classical Chinese option migrates to the closest
        // remaining Chinese UI instead of dropping to English.
        if stored == "lzh" { return .traditionalChinese }
        if stored.hasPrefix("zh") { return forSystemIdentifier(stored) }
        return AppLanguage(rawValue: stored) ?? .english
    }

    /// Match a full BCP-47 identifier. Chinese variants use the script/region
    /// to choose Simplified or Traditional; unsupported languages fall back to
    /// English.
    static func forSystemIdentifier(_ identifier: String) -> AppLanguage {
        let locale = Locale(identifier: identifier)
        let code = locale.language.languageCode?.identifier ?? ""
        if code == "zh" {
            let script = locale.language.script?.identifier ?? ""
            let region = locale.region?.identifier ?? ""
            if script == "Hant" || ["TW", "HK", "MO"].contains(region) {
                return .traditionalChinese
            }
            return .simplifiedChinese
        }
        switch code {
        case "en": return .english
        case "es": return .spanish
        case "ja": return .japanese
        case "ko": return .korean
        default: return .english
        }
    }
}

@MainActor
final class LocaleManager: ObservableObject {
    static let shared = LocaleManager()

    /// Mirrors the "appLanguage" UserDefaults key (whose single source of
    /// truth is SettingsStore). Kept in sync via defaults-change
    /// notifications so there is exactly one writer of the key.
    @Published private(set) var appLanguage: String
    private var defaultsObserver: NSObjectProtocol?

    private init() {
        let stored = UserDefaults.standard.string(forKey: "appLanguage") ?? Self.detectSystemLanguage()
        appLanguage = AppLanguage.resolve(stored).rawValue
        defaultsObserver = NotificationCenter.default.addObserver(
            forName: UserDefaults.didChangeNotification,
            object: UserDefaults.standard,
            queue: .main
        ) { [weak self] _ in
            // Pre-filter before the actor hop: most defaults writes (HUD
            // window size saves, sliders) never touch the language key.
            let stored = UserDefaults.standard.string(forKey: "appLanguage") ?? Self.detectSystemLanguage()
            let resolved = AppLanguage.resolve(stored).rawValue
            Task { @MainActor in
                guard let self, resolved != self.appLanguage else { return }
                self.appLanguage = resolved
            }
        }
    }

    /// Match the system's primary preferred language, then fall back to
    /// English when it is unsupported.
    nonisolated static func detectSystemLanguage() -> String {
        systemPreferredLanguage().rawValue
    }

    nonisolated static func systemPreferredLanguage() -> AppLanguage {
        guard let identifier = Locale.preferredLanguages.first else { return .english }
        return AppLanguage.forSystemIdentifier(identifier)
    }

    var currentLanguage: AppLanguage {
        AppLanguage.resolve(appLanguage)
    }

    func localized(_ key: String) -> String {
        guard let table = Self.translations[currentLanguage] else { return key }
        return table[key] ?? key
    }

